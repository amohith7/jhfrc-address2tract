"""Build docs/assets/hero_tracts.js, the tract outlines behind the hero demo.

The hero shows Hamilton County, Tennessee (home of JHFRC) as SVG paths so the
page can animate example addresses landing in their tracts without loading a
map library. Source: the same Census cartographic boundary file as the CLI and
the results map (cb_2024_us_tract_500k), projected to Tennessee State Plane
(EPSG:2274) so the county keeps its true shape.

Usage:
    python scripts/build_hero_map.py --zip path/to/cb_2024_us_tract_500k.zip
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import geopandas as gpd
from shapely.geometry import MultiPolygon, Polygon

OUT = Path(__file__).resolve().parent.parent / "docs" / "assets" / "hero_tracts.js"
STATE, COUNTY = "47", "065"
WIDTH = 400.0
SIMPLIFY_FEET = 120.0


def _ring(coords, minx: float, maxy: float, scale: float) -> str:
    """SVG path data for one ring in the viewBox."""
    pts = [f"{(x - minx) * scale:.1f} {(maxy - y) * scale:.1f}" for x, y in coords[:-1]]
    return "M" + "L".join(pts) + "Z"


def _path(geom, minx: float, maxy: float, scale: float) -> str:
    """SVG path data for a polygon or multipolygon, holes included."""
    polys = geom.geoms if isinstance(geom, MultiPolygon) else [geom]
    parts = []
    for poly in polys:
        if not isinstance(poly, Polygon):
            continue
        parts.append(_ring(poly.exterior.coords, minx, maxy, scale))
        parts.extend(_ring(r.coords, minx, maxy, scale) for r in poly.interiors)
    return "".join(parts)


def build(zip_path: Path) -> None:
    """Write the hero tract file."""
    gdf = gpd.read_file(f"zip://{zip_path}")
    gdf = gdf[(gdf.STATEFP == STATE) & (gdf.COUNTYFP == COUNTY)].to_crs(2274)
    gdf["geometry"] = gdf.geometry.simplify(SIMPLIFY_FEET, preserve_topology=True)
    minx, miny, maxx, maxy = gdf.total_bounds
    scale = WIDTH / (maxx - minx)
    height = round((maxy - miny) * scale, 1)
    tracts = []
    for row in gdf.sort_values("GEOID").itertuples():
        c = row.geometry.representative_point()
        tracts.append(
            {
                "g": row.GEOID,
                "d": _path(row.geometry, minx, maxy, scale),
                "x": round((c.x - minx) * scale, 1),
                "y": round((maxy - c.y) * scale, 1),
            }
        )
    data = {"w": WIDTH, "h": height, "tracts": tracts}
    text = (
        "/* Hamilton County, TN census tracts for the hero demo. Generated by\n"
        " * scripts/build_hero_map.py from Census cb_2024_us_tract_500k. */\n"
        "window.A2THero = " + json.dumps(data, separators=(",", ":")) + ";\n"
    )
    OUT.write_bytes(text.encode("utf-8"))
    print(
        f"{len(tracts)} tracts, viewBox {WIDTH:.0f} x {height}, {OUT.stat().st_size / 1e3:.0f} KB"
    )


def main() -> None:
    """Parse arguments and build the file."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--zip", type=Path, required=True, help="Downloaded cb_2024_us_tract_500k.zip"
    )
    build(parser.parse_args().zip)


if __name__ == "__main__":
    main()
